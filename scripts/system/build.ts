/**
 * Builds the machine-readable design system an agent reads instead of the stylesheets:
 * tokens/system.json (every token and part, with the facts derived from the code) and
 * tokens/llms.txt (the one-page index). Run: npm run system. `--check` fails when either is stale.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { usageComment } from "../../apps/web/src/lib/designCatalogue.js";
import {
  cssName,
  declarationsFor,
  hexFor,
  loadTokens,
  type Token,
  type TokenDocument,
} from "../buildTokens.js";
import { PARTS } from "./parts.js";
import type { BespokeControl, Part, PartSource, System, SystemToken } from "./types.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SRC = join(ROOT, "apps/web/src");
const STYLES = join(SRC, "styles");
export const SYSTEM_PATH = join(ROOT, "tokens/system.json");
export const LLMS_PATH = join(ROOT, "tokens/llms.txt");
const STYLES_TEST = join(STYLES, "styles.test.ts");

const GENERATED = "GENERATED by scripts/system/build.ts (npm run system). Do not edit.";

const posix = (path: string): string => path.split("\\").join("/");

function filesUnder(dir: string, extensions: string[], skip: (path: string) => boolean): string[] {
  const found: string[] = [];
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (skip(path)) continue;
    if (statSync(path).isDirectory()) found.push(...filesUnder(path, extensions, skip));
    else if (extensions.some((extension) => path.endsWith(extension))) found.push(path);
  }
  return found.sort();
}

const escapeRegex = (text: string): string => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** A rule that is about the class itself: some selector of its list begins with `.name`. */
const ruleOf = (name: string): RegExp => new RegExp(`(?:^|,)\\s*\\.${escapeRegex(name)}(?![\\w-])`);

interface Stylesheet {
  file: string;
  rules: { selector: string; body: string }[];
}

function readStylesheets(): Stylesheet[] {
  return readdirSync(STYLES)
    .filter((file) => file.endsWith(".css") && file !== "tokens.css")
    .sort()
    .map((file) => {
      const css = readFileSync(join(STYLES, file), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
      const rules = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(
        ([, selector = "", body = ""]) => ({
          selector: selector.trim(),
          body,
        }),
      );
      return { file, rules };
    });
}

/** The semantic and component custom properties, to keep a part's token list to the reusable ones. */
function reusableTokenNames(doc: TokenDocument): Set<string> {
  return new Set(
    doc.tokens.filter((token) => token.tier !== "primitive").map((token) => cssName(token.path)),
  );
}

/**
 * The class names a source file writes as classes: class and className attributes (or object
 * properties, as in `iconBtnHtml({ className })`), class:list entries and classList calls. A word that only looks like a class ("switch" in role="switch" or in
 * prose) is not a use, which is how a dead class once passed for a live part.
 */
export function classTokens(text: string): Set<string> {
  const found = new Set<string>();
  const add = (value: string): void => {
    for (const name of value.split(/\s+/)) if (/^[a-z][\w-]*$/i.test(name)) found.add(name);
  };
  for (const [, a = "", b = "", c = ""] of text.matchAll(
    /\bclass(?:Name)?\s*[=:]\s*(?:"([^"]*)"|'([^']*)'|\{`([^`]*)`\})/g,
  ))
    add(a || b || c);
  for (const [, list = ""] of text.matchAll(/\bclass:list\s*=\s*\{([^}]*)\}/g))
    for (const [, quoted = ""] of list.matchAll(/["'`]([^"'`]*)["'`]/g)) add(quoted);
  for (const [, args = ""] of text.matchAll(
    /classList\.(?:add|toggle|remove|contains)\(([^)]*)\)/g,
  ))
    for (const [, quoted = ""] of args.matchAll(/["'`]([^"'`]*)["'`]/g)) add(quoted);
  // The command center's scripts draw nodes with element(tag, className).
  for (const [, className = ""] of text.matchAll(
    /\belement\(\s*["'][^"']*["']\s*,\s*["']([^"']*)["']/g,
  ))
    add(className);
  // The Button draws its classes from its props, so the markup never writes them (D237).
  for (const [, props = ""] of text.matchAll(/<Button\b([^>]*)>/g)) {
    const variant = /\bvariant="(\w+)"/.exec(props)?.[1];
    const tone = /\btone="(\w+)"/.exec(props)?.[1];
    if (variant) found.add(`button-${variant}`);
    if (tone) found.add(`button-${tone}`);
  }
  for (const [, variant = "", tone] of text.matchAll(
    /\bbuttonClass\(\s*["'](\w+)["'](?:\s*,\s*["'](\w+)["'])?/g,
  )) {
    found.add(`button-${variant}`);
    if (tone) found.add(`button-${tone}`);
  }
  return found;
}

/** The apps that draw the system's parts: the reader and the command center, which imports its sheets. */
const APP_SOURCES = [SRC, join(ROOT, "apps/admin/src")];

export function sourceFiles(): { path: string; text: string; tokens: Set<string> }[] {
  return APP_SOURCES.flatMap((dir) =>
    filesUnder(
      dir,
      [".astro", ".tsx", ".ts", ".js"],
      (path) => path.endsWith(".test.ts") || posix(path).includes("/pages/design/"),
    ),
  ).map((path) => {
    const text = readFileSync(path, "utf8");
    return { path, text, tokens: classTokens(text) };
  });
}

function derive(
  source: PartSource,
  sheets: Stylesheet[],
  sources: { path: string; text: string; tokens: Set<string> }[],
  reusable: Set<string>,
): Part {
  const rulePatterns = source.classes.map(ruleOf);
  const styles = new Set<string>();
  const tokens = new Set<string>();
  for (const sheet of sheets)
    for (const rule of sheet.rules) {
      if (!rulePatterns.some((pattern) => pattern.test(rule.selector))) continue;
      styles.add(sheet.file);
      for (const [, name = ""] of rule.body.matchAll(/var\(\s*(--[\w-]+)/g))
        if (reusable.has(name)) tokens.add(name);
    }
  let usage = "";
  for (const file of styles) {
    usage = usageComment(file, `.${source.classes[0]}`, ROOT);
    if (usage) break;
  }
  const usedIn = sources.filter(({ tokens: used }) =>
    source.classes.some((name) => used.has(name)),
  ).length;
  return {
    ...source,
    styles: [...styles].sort(),
    usage,
    tokens: [...tokens].sort(),
    usedIn,
  };
}

/** The bespoke controls and their reasons, read from the list the style test enforces. */
export function readBespoke(text: string = readFileSync(STYLES_TEST, "utf8")): BespokeControl[] {
  const start = text.indexOf("const BESPOKE_CONTROLS");
  if (start < 0) return [];
  const end = text.indexOf("\n];", start);
  return [
    ...text.slice(start, end).matchAll(/\[\s*"([a-z0-9-]+)",\s*"((?:[^"\\]|\\.)*)"\s*,?\s*\]/g),
  ].map(([, name = "", reason = ""]) => ({ class: name, reason }));
}

function tokenRecord(token: Token, doc: TokenDocument): SystemToken {
  const render = (value: Token["value"]): string => {
    const declarations = declarationsFor(token, value, doc);
    const [first] = declarations;
    if (declarations.length === 1 && first) return first.value;
    const base = cssName(token.path);
    return declarations
      .map((declaration) => `${declaration.name.slice(base.length + 1)}: ${declaration.value}`)
      .join("; ");
  };
  const record: SystemToken = {
    name: cssName(token.path),
    tier: token.tier,
    type: token.type,
    light: render(token.value),
  };
  if (token.description) record.role = token.description;
  if (token.dark !== undefined) record.dark = render(token.dark);
  if (token.reducedMotion) record.reducedMotion = token.reducedMotion;
  // A translucent color has no single hex: the alpha would be dropped and an opaque value published.
  const translucent = [record.light, record.dark].some((value) => value?.includes(" / "));
  if (token.type === "color" && !translucent) {
    try {
      record.hex = {
        light: hexFor(doc, token.dotPath, "light"),
        dark: hexFor(doc, token.dotPath, "dark"),
      };
    } catch {
      // A translucent or non-literal color has no single hex.
    }
  }
  return record;
}

export function buildSystem(): System {
  const doc = loadTokens();
  const sheets = readStylesheets();
  const sources = sourceFiles();
  const reusable = reusableTokenNames(doc);
  const parts = PARTS.map((part) => derive(part, sheets, sources, reusable));
  return {
    generated: GENERATED,
    parts,
    bespoke: readBespoke().map((item) => {
      const owner = parts.find((part) => part.classes.includes(item.class));
      return owner ? { ...item, part: owner.id } : item;
    }),
    tokens: doc.tokens.map((token) => tokenRecord(token, doc)),
  };
}

const firstSentence = (text: string, limit: number): string => {
  const sentence = text.replace(/\s+/g, " ").split(/(?<=[.!?])\s/)[0] ?? "";
  return sentence.length > limit ? `${sentence.slice(0, limit - 1).trimEnd()}…` : sentence;
};

/** The one-page index: every part in a line, the color roles, the scales. Read this first. */
export function renderLlms(system: System): string {
  const lines: string[] = [
    "# Singularity design system",
    `<!-- ${GENERATED} -->`,
    "",
    "Pick a part from this list before writing a class or a value. A part that fits is used as it is; none fits means ask the owner. Never invent a control class.",
    'Detail of one: `npm run ds -- part <id>`. Search by need: `npm run ds -- find "<what you need>"`. Tokens: `npm run ds -- token <words>`. Everything: tokens/system.json.',
    "",
    "## Parts",
    "`id` classes: what it is. Use: when. Not: situation → part to use instead.",
  ];
  for (const part of system.parts) {
    const classes = part.classes
      .slice(0, 2)
      .map((name) => `.${name}`)
      .join(" ");
    const use = part.when.slice(0, 2).join("; ");
    const not = (part.not ?? [])
      .slice(0, 2)
      .map((item) => `${item.when} → ${item.use}`)
      .join("; ");
    lines.push(
      `- \`${part.id}\` ${classes}: ${part.summary} Use: ${use}.${not ? ` Not: ${not}.` : ""}`,
    );
  }
  lines.push(
    "",
    "## Color roles",
    "Components read only these (never a hex, never a primitive color).",
  );
  for (const token of system.tokens)
    if (token.tier === "semantic" && token.type === "color")
      lines.push(
        token.role ? `- ${token.name}: ${firstSentence(token.role, 90)}` : `- ${token.name}`,
      );
  lines.push("", "## Scales", "Read directly by components.");
  const scales = ["space", "radius", "stroke", "duration", "ease"];
  for (const scale of scales) {
    const items = system.tokens
      .filter((token) => token.tier === "primitive" && token.name.startsWith(`--${scale}-`))
      .map((token) => (token.light.length > 24 ? token.name : `${token.name} ${token.light}`));
    if (items.length > 0) lines.push(`- ${items.join(", ")}`);
  }
  const groups = new Map<string, number>();
  for (const token of system.tokens)
    if (token.tier === "component") {
      const group = token.name.split("-")[2] ?? "";
      groups.set(group, (groups.get(group) ?? 0) + 1);
    }
  lines.push(
    "",
    "## Component tokens",
    `Sizes and bindings per part: ${[...groups].map(([group, count]) => `${group} (${count})`).join(", ")}. List one with \`npm run ds -- token <group>\`.`,
    "",
    "## Bespoke controls",
    `${system.bespoke.filter((item) => !item.part).length} controls are built for one place (the player transport and dock, speed controls, source rows). They are not for reuse. ${system.bespoke.filter((item) => item.part).length} more belong to a part above and are used through it. \`npm run ds -- part bespoke\` lists all with the reason.`,
    "",
  );
  return lines.join("\n");
}

export function renderSystemJson(system: System): string {
  return `${JSON.stringify(system, (key, value) => (key === "usedIn" ? undefined : value), 2)}\n`;
}

function main(): void {
  const system = buildSystem();
  const outputs: [string, string][] = [
    [SYSTEM_PATH, renderSystemJson(system)],
    [LLMS_PATH, renderLlms(system)],
  ];
  if (process.argv.includes("--check")) {
    const stale = outputs.filter(
      ([path, text]) => !existsSync(path) || readFileSync(path, "utf8") !== text,
    );
    if (stale.length > 0) {
      for (const [path] of stale)
        console.error(`${relative(ROOT, path)} is stale. Run: npm run system`);
      process.exit(1);
    }
    console.log("system.json and llms.txt are up to date");
    return;
  }
  for (const [path, text] of outputs) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text, "utf8");
    console.log(`Wrote ${relative(ROOT, path)} (${text.length} bytes)`);
  }
}

const isMain =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) main();
