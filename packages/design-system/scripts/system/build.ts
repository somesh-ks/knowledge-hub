/**
 * Builds the machine-readable design system an agent reads instead of the stylesheets:
 * tokens/system.json (every token and part, with the facts derived from the code) and
 * tokens/llms.txt (the one-page index). The package builds it alone; an app that draws the system
 * passes in where it styles and writes each part (scripts/system.ts at the repository root, which
 * `npm run system` runs; `--check` fails when either file is stale).
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  aliasTarget,
  cssName,
  declarationsFor,
  hexFor,
  loadTokens,
  type Token,
  type TokenDocument,
} from "../buildTokens.js";
import { PARTS } from "./parts.js";
import type { BespokeControl, Part, PartSource, System, SystemToken } from "./types.js";
import { usageComment } from "./usage.js";

/** The package that holds the system. */
const PACKAGE = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const SYSTEM_PATH = join(PACKAGE, "tokens/system.json");
export const LLMS_PATH = join(PACKAGE, "tokens/llms.txt");

/**
 * What an app that draws the system passes in (D382 step 4c), so the package never reads app code
 * of its own accord. Paths in the file are written relative to `root`.
 */
export interface SystemInput {
  root: string;
  /** The app's stylesheet folders, read beside the package's: a part may be styled in either. */
  styles: string[];
  /** The app's source folders, whose markup counts as a use, beside the package's own src/. */
  sources: string[];
  /** The app's style test, whose BESPOKE_CONTROLS list names the controls built for one place. */
  bespoke?: string;
}

/** The package alone: no app styles a part or writes one. */
const ALONE: SystemInput = { root: PACKAGE, styles: [], sources: [] };

const GENERATED = "GENERATED by scripts/system/build.ts (npm run system). Do not edit.";

const posix = (path: string): string => path.split("\\").join("/");

function filesUnder(dir: string, extensions: string[], skip: (path: string) => boolean): string[] {
  const found: string[] = [];
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (skip(path)) continue;
    if (statSync(path).isDirectory()) found.push(...filesUnder(path, extensions, skip));
    else if (extensions.some((extension) => path.endsWith(extension))) found.push(path);
  }
  return found.sort();
}

const escapeRegex = (text: string): string => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** A rule that is about the class itself: some selector of its list begins with `.name`, or with `tag.name`. */
const ruleOf = (name: string): RegExp =>
  new RegExp(`(?:^|,)\\s*(?:[a-z][\\w-]*)?\\.${escapeRegex(name)}(?![\\w-])`);

interface Stylesheet {
  file: string;
  rules: { selector: string; body: string }[];
}

function readStylesheets(input: SystemInput): Stylesheet[] {
  const STYLE_DIRS = [join(PACKAGE, "styles"), ...input.styles];
  // By name across the folders, as when they were one: a part's usage is the first sheet's comment.
  return STYLE_DIRS.flatMap((dir) =>
    readdirSync(dir)
      .filter((name) => name.endsWith(".css") && name !== "tokens.css")
      .map((name) => ({ name, path: join(dir, name) })),
  )
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .map(({ path }) => {
      const file = posix(relative(input.root, path));
      const css = readFileSync(path, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
      const rules = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(
        ([, selector = "", body = ""]) => ({
          selector: selector.trim(),
          body,
        }),
      );
      return { file, rules };
    });
}

/** The semantic and component custom properties, to keep a part's token list to the reusable ones. */
function reusableTokenNames(doc: TokenDocument): Set<string> {
  return new Set(
    doc.tokens.filter((token) => token.tier !== "primitive").map((token) => cssName(token.path)),
  );
}

/**
 * The class names a source file writes as classes: class and className attributes (or object
 * properties, as in `iconBtnHtml({ className })`), class:list entries and classList calls. A word that only looks like a class ("switch" in role="switch" or in
 * prose) is not a use, which is how a dead class once passed for a live part.
 */
export function classTokens(text: string): Set<string> {
  const found = new Set<string>();
  const add = (value: string): void => {
    for (const name of value.split(/\s+/)) if (/^[a-z][\w-]*$/i.test(name)) found.add(name);
  };
  for (const [, a = "", b = "", c = ""] of text.matchAll(
    /\bclass(?:Name)?\s*[=:]\s*(?:"([^"]*)"|'([^']*)'|\{`([^`]*)`\})/g,
  ))
    add(a || b || c);
  for (const [, list = ""] of text.matchAll(/\bclass:list\s*=\s*\{([^}]*)\}/g))
    for (const [, quoted = ""] of list.matchAll(/["'`]([^"'`]*)["'`]/g)) add(quoted);
  for (const [, args = ""] of text.matchAll(
    /classList\.(?:add|toggle|remove|contains)\(([^)]*)\)/g,
  ))
    for (const [, quoted = ""] of args.matchAll(/["'`]([^"'`]*)["'`]/g)) add(quoted);
  // The command center's scripts draw nodes with element(tag, className).
  for (const [, className = ""] of text.matchAll(
    /\belement\(\s*["'][^"']*["']\s*,\s*["']([^"']*)["']/g,
  ))
    add(className);
  // The Button draws its classes from its props, so the markup never writes them (D237).
  for (const [, props = ""] of text.matchAll(/<Button\b([^>]*)>/g)) {
    const variant = /\bvariant="(\w+)"/.exec(props)?.[1];
    const tone = /\btone="(\w+)"/.exec(props)?.[1];
    const size = /\bsize="(\w+)"/.exec(props)?.[1];
    if (variant) found.add(`button-${variant}`);
    if (tone) found.add(`button-${tone}`);
    if (size) found.add(`button-${size}`);
  }
  for (const [, variant = "", tone] of text.matchAll(
    /\bbuttonClass\(\s*["'](\w+)["'](?:\s*,\s*["'](\w+)["'])?/g,
  )) {
    found.add(`button-${variant}`);
    if (tone) found.add(`button-${tone}`);
  }
  const code = text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
  // The Icon is drawn by the tag, the island's tag or the class helper; the large size by its prop.
  if (/<(?:Lazy)?Icon\b|\biconClass\(|\biconHtml\(/.test(code)) found.add("icon-glyph");
  if (/<(?:Lazy)?Icon\b[^>]*\bsize="lg"|\bicon(?:Class|Html)\([^)]*["']lg["']/.test(code)) {
    found.add("icon-glyph-lg");
  }
  if (/<PlayPauseIcons\b[^>]*\bsize="lg"/.test(code)) found.add("icon-glyph-lg");
  // The Badge is a single-class component, drawn by the tag or by the class helper.
  if (/<Badge\b|\bbadgeClass\(/.test(code)) found.add("badge-label");
  // The Switch and the Slider are single-class components, drawn by the tag or by the class helper.
  if (/<Switch\b|\bswitchClass\(/.test(code)) found.add("switch-input");
  if (/<Slider\b|\bsliderClass\(/.test(code)) found.add("slider-input");
  // The Field is drawn by the tag (not Base UI's Field.Root) or by the class helper, for a select.
  if (/<Field(?![\w.])|\bfieldClass\(/.test(code)) found.add("field-input");
  // The Select is drawn by the tag or by the class helper, in the variant it names (outlined by default).
  if (/<Select\b/.test(code)) {
    const tonal = [...code.matchAll(/<Select\b[^>]*\bvariant="tonal"/g)].length;
    const all = [...code.matchAll(/<Select\b/g)].length;
    if (tonal > 0) found.add("select-tonal");
    if (all > tonal) found.add("select-outlined");
  }
  // The Menu: its list by the tag or the class helper, its rows likewise (the danger tone by its name).
  if (/<Menu\b|\bmenuListClass\(|\bmenuSheetClass\(/.test(code)) {
    found.add("menu-list");
    found.add("menu-sheet");
  }
  if (/<MenuItem\b|\bmenuItemClass\(/.test(code)) found.add("menu-item");
  if (
    /<MenuItem\b[^>]*\btone="danger"|\bmenuItemClass\(\s*["']danger["']|tone:\s*["']danger["']/.test(
      code,
    )
  ) {
    found.add("menu-item-danger");
  }
  // The tiles and the value come by their class helpers.
  if (/\bmenuTilesClass\(/.test(code)) found.add("menu-tiles");
  if (/\bmenuTileClass\(/.test(code)) found.add("menu-tile");
  if (/\bmenuItemValueClass\(/.test(code)) found.add("menu-item-value");
  // The Dialog: the tag, its actions row (stacked by its prop), its heading, or the class helpers.
  if (/<Dialog\b|\bdialogClass\(/.test(code)) {
    found.add("dialog-panel");
    found.add("dialog-body");
  }
  // The Sheet: the tag (its header and body come with it) or the helpers a script builds with.
  if (/<Sheet\b|\bsheetClass\(/.test(code)) {
    found.add("sheet-side");
    found.add("sheet-head");
    found.add("sheet-body");
    found.add("sheet-title");
  }
  if (/\bsheetHeadClass\(|\bsheetHeadHtml\(|<SheetHeader\b/.test(code)) {
    found.add("sheet-head");
    found.add("sheet-title");
  }
  if (/\bsheetBodyClass\(/.test(code)) found.add("sheet-body");
  if (/\bsheetTitleClass\(/.test(code)) found.add("sheet-title");
  // The Drawer: SheetFrame draws it from the helpers.
  for (const [helper, name] of [
    ["drawerScrimClass", "drawer-scrim"],
    ["drawerViewportClass", "drawer-viewport"],
    ["drawerPopupClass", "drawer-popup"],
    ["drawerPanelClass", "drawer-panel"],
  ] as const) {
    if (code.includes(`${helper}(`)) found.add(name);
  }
  if (/<DialogActions\b|\bdialogActionsClass\(/.test(code)) found.add("dialog-actions");
  if (/<DialogActions\b[^>]*\bstacked\b|\bdialogActionsClass\(\s*true/.test(code)) {
    found.add("dialog-actions-stacked");
  }
  // The Banner is drawn by the tag or by the class helper; its parts come with it.
  if (/<Banner\b|\bbannerClass\(/.test(code)) {
    for (const name of ["banner-notice", "banner-text", "banner-title", "banner-body"])
      found.add(name);
  }
  for (const [, variant = "outlined"] of code.matchAll(/\bselectClass\(\s*(?:["'](\w+)["'])?/g)) {
    found.add(`select-${variant}`);
  }
  return found;
}

/** The files that draw the system's parts: the app's, then the package's own. */
export function sourceFiles(
  input: SystemInput = ALONE,
): { path: string; text: string; tokens: Set<string> }[] {
  const SOURCE_DIRS = [...input.sources, join(PACKAGE, "src")];
  return SOURCE_DIRS.flatMap((dir) =>
    filesUnder(
      dir,
      [".astro", ".tsx", ".ts", ".js"],
      (path) => path.endsWith(".test.ts") || posix(path).includes("/pages/design/"),
    ),
  ).map((path) => {
    const text = readFileSync(path, "utf8");
    const tokens = classTokens(text);
    // The component files define the two controls; only a caller outside them is a use.
    if (posix(path).includes("/design-system/")) {
      tokens.delete("badge-label");
      tokens.delete("icon-glyph");
      tokens.delete("icon-glyph-lg");
      tokens.delete("switch-input");
      tokens.delete("slider-input");
      tokens.delete("field-input");
      tokens.delete("select-outlined");
      tokens.delete("select-tonal");
      tokens.delete("menu-list");
      tokens.delete("menu-item");
      tokens.delete("menu-sheet");
      tokens.delete("menu-item-danger");
      tokens.delete("menu-tiles");
      tokens.delete("menu-tile");
      tokens.delete("menu-item-value");
      for (const name of ["banner-notice", "banner-text", "banner-title", "banner-body"]) {
        tokens.delete(name);
      }
      for (const name of [
        "dialog-panel",
        "dialog-body",
        "dialog-actions",
        "dialog-actions-stacked",
        "sheet-side",
        "sheet-head",
        "sheet-body",
        "sheet-title",
        "drawer-scrim",
        "drawer-viewport",
        "drawer-popup",
        "drawer-panel",
      ]) {
        tokens.delete(name);
      }
    }
    return { path, text, tokens };
  });
}

function derive(
  source: PartSource,
  sheets: Stylesheet[],
  sources: { path: string; text: string; tokens: Set<string> }[],
  reusable: Set<string>,
  root: string,
): Part {
  const rulePatterns = source.classes.map(ruleOf);
  const styles = new Set<string>();
  const tokens = new Set<string>();
  for (const sheet of sheets)
    for (const rule of sheet.rules) {
      if (!rulePatterns.some((pattern) => pattern.test(rule.selector))) continue;
      styles.add(sheet.file);
      for (const [, name = ""] of rule.body.matchAll(/var\(\s*(--[\w-]+)/g))
        if (reusable.has(name)) tokens.add(name);
    }
  let usage = "";
  for (const file of styles) {
    usage = usageComment(file, `.${source.classes[0]}`, root);
    if (usage) break;
  }
  const usedIn = sources.filter(({ tokens: used }) =>
    source.classes.some((name) => used.has(name)),
  ).length;
  return {
    ...source,
    styles: [...styles].sort(),
    usage,
    tokens: [...tokens].sort(),
    usedIn,
  };
}

/** The bespoke controls and their reasons, read from the list the style test enforces. */
export function readBespoke(text: string): BespokeControl[] {
  const start = text.indexOf("const BESPOKE_CONTROLS");
  if (start < 0) return [];
  const end = text.indexOf("\n];", start);
  return [
    ...text.slice(start, end).matchAll(/\[\s*"([a-z0-9-]+)",\s*"((?:[^"\\]|\\.)*)"\s*,?\s*\]/g),
  ].map(([, name = "", reason = ""]) => ({ class: name, reason }));
}

/** A haptic is read by script, so it is named `haptic-open`, never as a custom property that does not exist. */
function hapticRecord(token: Token): SystemToken {
  const intent = token.tier === "semantic";
  const target = aliasTarget(token.value);
  const value = token.value;
  let light = target ? target.replace("primitive.haptic.", "pattern ") : "";
  if (!target && typeof value === "object" && value !== null && !Array.isArray(value)) {
    const ios = value.ios as { ticks: number; gap_ms: number };
    light =
      `android ${(value.android as number[]).join(" ") || "nothing"} ms; ` +
      `iphone ${ios.ticks} tick${ios.ticks === 1 ? "" : "s"}${ios.gap_ms ? `, ${ios.gap_ms} ms apart` : ""}`;
  }
  const record: SystemToken = {
    name: `haptic-${intent ? "" : "pattern-"}${token.path[token.path.length - 1]}`,
    tier: token.tier,
    type: token.type,
    light,
  };
  if (token.description) record.role = token.description;
  return record;
}

function tokenRecord(token: Token, doc: TokenDocument): SystemToken {
  if (token.type === "singularity-haptic") return hapticRecord(token);
  const render = (value: Token["value"]): string => {
    const declarations = declarationsFor(token, value, doc);
    const [first] = declarations;
    if (declarations.length === 1 && first) return first.value;
    const base = cssName(token.path);
    return declarations
      .map((declaration) => `${declaration.name.slice(base.length + 1)}: ${declaration.value}`)
      .join("; ");
  };
  const record: SystemToken = {
    name: cssName(token.path),
    tier: token.tier,
    type: token.type,
    light: render(token.value),
  };
  if (token.description) record.role = token.description;
  if (token.dark !== undefined) record.dark = render(token.dark);
  if (token.reducedMotion) record.reducedMotion = token.reducedMotion;
  // A translucent color has no single hex: the alpha would be dropped and an opaque value published.
  const translucent = [record.light, record.dark].some((value) => value?.includes(" / "));
  if (token.type === "color" && !translucent) {
    try {
      record.hex = {
        light: hexFor(doc, token.dotPath, "light"),
        dark: hexFor(doc, token.dotPath, "dark"),
      };
    } catch {
      // A translucent or non-literal color has no single hex.
    }
  }
  return record;
}

export function buildSystem(input: SystemInput = ALONE): System {
  const doc = loadTokens();
  const sheets = readStylesheets(input);
  const sources = sourceFiles(input);
  const reusable = reusableTokenNames(doc);
  const parts = PARTS.map((part) => derive(part, sheets, sources, reusable, input.root));
  const bespoke = input.bespoke ? readBespoke(readFileSync(input.bespoke, "utf8")) : [];
  return {
    generated: GENERATED,
    parts,
    bespoke: bespoke.map((item) => {
      const owner = parts.find((part) => part.classes.includes(item.class));
      return owner ? { ...item, part: owner.id } : item;
    }),
    tokens: doc.tokens.map((token) => tokenRecord(token, doc)),
  };
}

const firstSentence = (text: string, limit: number): string => {
  const sentence = text.replace(/\s+/g, " ").split(/(?<=[.!?])\s/)[0] ?? "";
  return sentence.length > limit ? `${sentence.slice(0, limit - 1).trimEnd()}…` : sentence;
};

/** The one-page index: every part in a line, the color roles, the scales. Read this first. */
export function renderLlms(system: System): string {
  const lines: string[] = [
    "# Singularity design system",
    `<!-- ${GENERATED} -->`,
    "",
    "Pick a part from this list before writing a class or a value. A part that fits is used as it is; none fits means ask the owner. Never invent a control class.",
    'Detail of one: `npm run ds -- part <id>`. Search by need: `npm run ds -- find "<what you need>"`. Tokens: `npm run ds -- token <words>`. Everything: tokens/system.json.',
    "",
    "## Parts",
    "`id` classes: what it is. Use: when. Not: situation → part to use instead.",
  ];
  for (const part of system.parts) {
    const classes = part.classes
      .slice(0, 2)
      .map((name) => `.${name}`)
      .join(" ");
    const use = part.when.slice(0, 2).join("; ");
    const not = (part.not ?? [])
      .slice(0, 1)
      .map((item) => `${item.when} → ${item.use}`)
      .join("; ");
    lines.push(
      `- \`${part.id}\` ${classes}: ${part.summary} Use: ${use}.${not ? ` Not: ${not}.` : ""}`,
    );
  }
  lines.push(
    "",
    "## Color roles",
    "Components read only these (never a hex, never a primitive color).",
  );
  for (const token of system.tokens)
    if (token.tier === "semantic" && token.type === "color")
      lines.push(
        token.role ? `- ${token.name}: ${firstSentence(token.role, 90)}` : `- ${token.name}`,
      );
  // A fill's hover and press are derived colours (D317): one line names them, not 26.
  const stated = new Set(
    system.tokens
      .filter((token) => token.tier === "semantic" && token.type === "singularity-state-color")
      .map((token) => token.name.replace(/-(hover|pressed)$/, "")),
  );
  if (stated.size > 0)
    lines.push(`- <fill>-hover and <fill>-pressed for ${[...stated].join(", ")}: its state fills`);
  lines.push("", "## Scales", "Read directly by components.");
  const scales = ["space", "radius", "stroke", "duration", "ease"];
  for (const scale of scales) {
    // Corners are read through the semantic `--shape-*` scale, which a style redraws; only the
    // round pill is read as a primitive.
    const prefix = `--${scale}-`;
    const items = system.tokens
      .filter(
        (token) =>
          token.tier === "primitive" &&
          token.name.startsWith(prefix) &&
          (scale !== "radius" || token.name === "--radius-round"),
      )
      .map((token) => {
        const name = token.name.slice(prefix.length);
        return token.light.length > 24 ? name : `${name} ${token.light}`;
      });
    if (items.length > 0) lines.push(`- ${prefix}{${items.join(", ")}}`);
    if (scale === "radius")
      lines.push("- --shape-{xs, sm, md, lg, xl, sheet, 2xl}: corners, a style redraws them");
  }
  const groups = new Map<string, number>();
  for (const token of system.tokens)
    if (token.tier === "component") {
      const group = token.name.split("-")[2] ?? "";
      groups.set(group, (groups.get(group) ?? 0) + 1);
    }
  lines.push(
    "",
    "## Component tokens",
    `Sizes per part: ${[...groups].map(([group, count]) => `${group} (${count})`).join(", ")}. List one with \`npm run ds -- token <group>\`.`,
    "",
    "## Bespoke controls",
    `${system.bespoke.filter((item) => !item.part).length} controls are built for one place (the player transport and dock, speed controls, source rows), not for reuse. ${system.bespoke.filter((item) => item.part).length} more are used through a part above. \`npm run ds -- part bespoke\` lists them.`,
    "",
  );
  return lines.join("\n");
}

export function renderSystemJson(system: System): string {
  return `${JSON.stringify(system, (key, value) => (key === "usedIn" ? undefined : value), 2)}\n`;
}

/** Writes both files, or with `check` exits 1 when either differs from what `input` builds. */
export function writeSystem(input: SystemInput, check: boolean): void {
  const system = buildSystem(input);
  const outputs: [string, string][] = [
    [SYSTEM_PATH, renderSystemJson(system)],
    [LLMS_PATH, renderLlms(system)],
  ];
  if (check) {
    const stale = outputs.filter(
      ([path, text]) => !existsSync(path) || readFileSync(path, "utf8") !== text,
    );
    if (stale.length > 0) {
      for (const [path] of stale)
        console.error(`${relative(input.root, path)} is stale. Run: npm run system`);
      process.exit(1);
    }
    console.log("system.json and llms.txt are up to date");
    return;
  }
  for (const [path, text] of outputs) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text, "utf8");
    console.log(`Wrote ${relative(input.root, path)} (${text.length} bytes)`);
  }
}
